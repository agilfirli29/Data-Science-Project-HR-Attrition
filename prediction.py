import pandas as pd
import joblib

def predict_attrition(data):
    # Load model dan tools
    model = joblib.load('model/best_hr_model.pkl')
    scaler = joblib.load('model/hr_scaler.pkl')
    model_columns = joblib.load('model/hr_model_columns.pkl')

    # Preprocessing input
    df_input = pd.DataFrame([data])
    df_encoded = pd.get_dummies(df_input)

    # Menyesuaikan kolom dengan saat training
    for col in model_columns:
        if col not in df_encoded.columns:
            df_encoded[col] = 0
    df_encoded = df_encoded[model_columns]

    # Scaling & Prediksi
    df_scaled = pd.DataFrame(scaler.transform(df_encoded), columns=df_encoded.columns)
    prediction = model.predict(df_scaled)

    if prediction[0] == 1:
        print("⚠️ PREDIKSI: Karyawan ini BERISIKO TINGGI untuk Resign.")
    else:
        print("✅ PREDIKSI: Karyawan ini AMAN (Cenderung Bertahan).")

